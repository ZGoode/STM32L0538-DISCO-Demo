/* Display test: Example 1 - Basic (B/W) -------------------------------------
 *
 * Exercises the drawing API (epaper_* primitives and gfx_* text) on one screen:
 * two font sizes, a line, an outline rectangle, a filled rectangle with a fine
 * checkerboard cut out of it, a hollow and a filled circle, and a diagonal
 * crossing all of them. Rendered in plain B/W with epaper_update().
 */
static void draw_example1_basic(void)
{
  uint16_t w = epaper_width(), h = epaper_height();
  uint8_t  s = ui_scale();
  uint16_t top = (uint16_t)(GFX_CHAR_H * s + 5U);

  draw_title("Example 1 - Basic");

  /* Font sizes: the same string at two scales (fixed 5x7 font, integer scaled). */
  gfx_text(2, top, "Aa1", 1, EPAPER_BLACK);
  gfx_text((uint16_t)(2U + gfx_text_width("Aa1 ", 1)), top, "Aa1", 2, EPAPER_BLACK);

  uint16_t y0       = (uint16_t)(top + GFX_CHAR_H * 2U + 4U);
  uint16_t footer_y = (uint16_t)(h - 9U);
  uint16_t ch       = (footer_y > (uint16_t)(y0 + 6U)) ? (uint16_t)(footer_y - y0 - 2U) : 6U;
  uint16_t cellw    = (uint16_t)(w / 4U);

  epaper_hline(2, y0, (uint16_t)(w - 4U), EPAPER_BLACK);
  epaper_rect(0, (uint16_t)(y0 + 2U), w, ch, EPAPER_BLACK);

  uint16_t iw = (uint16_t)(cellw - 6U), ih = (uint16_t)(ch - 6U);
  uint16_t iy = (uint16_t)(y0 + 5U);

  /* Cell 0: outline rectangle. */
  epaper_rect(3U, iy, iw, ih, EPAPER_BLACK);

  /* Cell 1: filled rectangle with a fine checkerboard punched into it. */
  uint16_t x1 = (uint16_t)(3U + cellw);
  epaper_fill_rect(x1, iy, iw, ih, EPAPER_BLACK);
  for (uint16_t yy = 0; yy < ih; yy += 2U)
    for (uint16_t xx = 0; xx < iw; xx += 2U)
      if (((xx / 2U + yy / 2U) & 1U) == 0U)
        epaper_set_pixel((uint16_t)(x1 + xx), (uint16_t)(iy + yy), EPAPER_WHITE);

  /* Cell 2: hollow circle, cell 3: filled circle. */
  uint16_t rad = (uint16_t)((iw < ih ? iw : ih) / 2U);
  if (rad < 3U) rad = 3U;
  uint16_t cx2 = (uint16_t)(3U + 2U * cellw + iw / 2U);
  uint16_t cy  = (uint16_t)(iy + ih / 2U);
  epaper_circle(cx2, cy, rad, EPAPER_BLACK);
  uint16_t cx3 = (uint16_t)(3U + 3U * cellw + iw / 2U);
  epaper_fill_circle(cx3, cy, rad, EPAPER_BLACK);

  /* Diagonal across the whole content band, drawn last so it crosses the shapes. */
  for (uint16_t x = 0; x < w; x++)
  {
    uint16_t yy = (uint16_t)(y0 + 2U + ((uint32_t)x * (ch - 1U)) / (w - 1U));
    epaper_set_pixel(x, yy, EPAPER_BLACK);
  }

  draw_footer("B1/touch: next   hold: menu");
}

/* Display test: Example 2 - 4-level grayscale ------------------------------
 *
 * Four large swatches in the native shades (white, light gray, dark gray,
 * black), each holding a digit drawn in the opposite shade to show text and
 * shapes at a non-default gray value, plus a small ramp strip showing the
 * black-to-white transition across the four levels.
 * epaper_update_gray() calls this twice per refresh (once per shade bit), so
 * it only draws and keeps no state of its own.
 */
static void draw_example2_4gray(void)
{
  static const uint8_t shade[4]    = { EPAPER_WHITE, EPAPER_GRAY_LIGHT, EPAPER_GRAY_DARK, EPAPER_BLACK };
  static const uint8_t ramp[4]     = { EPAPER_BLACK, EPAPER_GRAY_DARK, EPAPER_GRAY_LIGHT, EPAPER_WHITE };
  static const char *const name[4] = { "WHITE", "LIGHT", "DARK", "BLACK" };
  uint16_t W = epaper_width(), H = epaper_height();
  uint16_t top      = (uint16_t)(GFX_CHAR_H * ui_scale() + 5U);
  uint16_t footer_y = (uint16_t)(H - 9U);
  uint16_t avail    = (uint16_t)(footer_y - top);
  uint16_t cap_h    = 9U;
  uint16_t strip_h  = (avail >= 60U) ? 10U : 6U;
  uint16_t h        = (uint16_t)(avail - cap_h - strip_h - 5U);   /* main swatch height */
  uint16_t bw       = (uint16_t)((W - 8U - 3U * 4U) / 4U);

  epaper_clear(EPAPER_WHITE);
  draw_title("Example 2 - 4 Gray");
  for (uint8_t i = 0; i < 4; i++)
  {
    uint16_t x  = (uint16_t)(4U + i * (bw + 4U));
    uint16_t tw = gfx_text_width(name[i], 1);
    epaper_fill_rect(x, top, bw, h, shade[i]);
    epaper_rect(x, top, bw, h, EPAPER_BLACK);

    /* Digit drawn in the opposite shade, so it is visible on any swatch. */
    char idx[2] = { (char)('0' + i), 0 };
    epaper_fill_rect((uint16_t)(x + bw / 2U - 4U), (uint16_t)(top + h / 2U - 5U), 8, 10, shade[3U - i]);
    gfx_text((uint16_t)(x + bw / 2U - 2U), (uint16_t)(top + h / 2U - 4U), idx, 1, shade[i]);

    gfx_text((uint16_t)(x + (bw - tw) / 2U), (uint16_t)(top + h + 3U), name[i], 1, EPAPER_BLACK);
  }

  /* Transition strip: the same four levels, black to white from left to right. */
  uint16_t sy = (uint16_t)(top + h + 3U + cap_h + 2U);
  for (uint8_t i = 0; i < 4; i++)
    epaper_fill_rect((uint16_t)(4U + i * (bw + 4U)), sy, bw, strip_h, ramp[i]);

  draw_footer("Any press: next   hold: menu");
}

/* Dithering shared by Examples 3 and 4 --------------------------------------
 *
 * Each pixel of a gray refresh is driven to one of 4 states: both panels'
 * RAM holds 2 bits per pixel, and on the GDEY0213B74 (SSD1680) those 2 bits
 * select 1 of 4 waveform LUT entries (see ssd1680_gray4_lut and
 * panel_gray_plane_done() in epaper.c). A single refresh cannot produce more
 * than 4 optical states per pixel.
 *
 * In-between levels are approximated by spatial dithering of the four native
 * shades. A 4x4 ordered (Bayer) matrix mixes the two nearest native shades
 * pixel by pixel, so a small tile's average reflectance approximates the
 * requested level. Over the 3 gaps between the 4 shades this gives
 * 3 * 16 + 1 = 49 target brightnesses, at the cost of spatial resolution.
 * Every dithered pixel is really driven to one of the panel's 4 states, and
 * the refresh is the regular epaper_update_gray() waveform.
 */
#define DITHER_STEPS   16U
#define DITHER_LEVELS  48U   /* 3 gaps between the 4 native shades * 16 steps */

static const uint8_t dither_bayer4x4[4][4] = {
  {  0,  8,  2, 10 },
  { 12,  4, 14,  6 },
  {  3, 11,  1,  9 },
  { 15,  7, 13,  5 }
};

/* level: 0 (black) .. DITHER_LEVELS (white). Returns the EPAPER_* shade to
 * plot at (x, y) so that a 4x4 tile's average approximates `level`. */
static uint8_t dither_color(uint16_t x, uint16_t y, uint16_t level)
{
  static const uint8_t shade[4] = { EPAPER_BLACK, EPAPER_GRAY_DARK, EPAPER_GRAY_LIGHT, EPAPER_WHITE };
  if (level > DITHER_LEVELS) level = DITHER_LEVELS;
  uint8_t gap = (uint8_t)(level / DITHER_STEPS);
  if (gap > 2U) gap = 2U;
  uint8_t frac = (uint8_t)(level - (uint16_t)gap * DITHER_STEPS);   /* 0..16 */
  uint8_t thr  = dither_bayer4x4[y & 3U][x & 3U];                   /* 0..15 */
  return shade[(frac > thr) ? (uint8_t)(gap + 1U) : gap];
}

