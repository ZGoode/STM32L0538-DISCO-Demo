/* Unrecoverable error: blink the red LED fast and repeat a message on the
 * virtual COM port. A typical cause is a wrong EPAPER_DISPLAY setting. */
static void fatal(const char *msg)
{
  uint32_t n = 0;
  for (;;)
  {
    if ((n++ % 20U) == 0U) board_log("ERROR: %s (EPAPER_DISPLAY=%u, %s)",
                                     msg, epaper_display_id(), epaper_name());
    board_led_red(true);  HAL_Delay(100);
    board_led_red(false); HAL_Delay(100);
  }
}

static void show(void)                    /* push framebuffer to the panel */
{
  if (!epaper_update()) fatal("e-paper BUSY timeout - wrong display selected?");
}

