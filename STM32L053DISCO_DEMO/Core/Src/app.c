/* Main menu: a vertically scrolling list. The row height is fixed; only as many
 * items as fit are shown, and the visible window follows `sel`. The window is
 * recomputed from `sel` on every draw, so no scroll offset has to be stored:
 * `sel` moves by one item at a time. */
static void draw_menu(void)
{
  uint8_t  s   = ui_scale();
  uint16_t lh  = (uint16_t)(GFX_CHAR_H * s + 1U);          /* fixed row height */
  uint16_t y0  = (uint16_t)(GFX_CHAR_H * s + 5U);
  uint16_t room = (uint16_t)(epaper_height() - 9U - y0);   /* space above the footer line */

  uint8_t visible = (uint8_t)(room / lh);                  /* items that actually fit */
  if (visible < 1U) visible = 1U;

  /* Smallest scroll offset that keeps `sel` inside the visible window. */
  uint8_t top = (uint8_t)((sel >= visible) ? (sel - visible + 1U) : 0U);
  uint8_t last = (uint8_t)(top + visible);
  if (last > MENU_COUNT) last = MENU_COUNT;

  bool     scrollable = (MENU_COUNT > visible);
  uint16_t sb_w  = scrollable ? 4U : 0U;      /* reserve a thin column for the scrollbar */
  uint16_t row_w = (uint16_t)(epaper_width() - sb_w);

  draw_title("STM32L0538-DISCO");
  for (uint8_t i = top; i < last; i++)
  {
    uint16_t y = (uint16_t)(y0 + (i - top) * lh);
    if (i == sel)
    {
      epaper_fill_rect(0, (uint16_t)(y - 1U), row_w, lh, EPAPER_BLACK);
      gfx_text(6, y, menu_text[i], s, EPAPER_WHITE);
    }
    else
    {
      gfx_text(6, y, menu_text[i], s, EPAPER_BLACK);
    }
  }

  if (scrollable)
  {
    /* Scroll indicator: a thin track spanning the list area and a thumb
     * showing which slice of the MENU_COUNT items is visible. */
    uint16_t track_x = (uint16_t)(epaper_width() - 2U);
    epaper_vline(track_x, y0, room, EPAPER_BLACK);

    uint16_t thumb_h = (uint16_t)(((uint32_t)room * visible) / MENU_COUNT);
    if (thumb_h < 3U) thumb_h = 3U;
    uint16_t travel   = (uint16_t)(room - thumb_h);
    uint16_t thumb_y  = (uint16_t)(y0 + ((uint32_t)travel * top) / (uint16_t)(MENU_COUNT - visible));
    epaper_fill_rect((uint16_t)(track_x - 1U), thumb_y, 3, thumb_h, EPAPER_BLACK);
  }

  draw_footer("B1: move  hold: select");
}

static void draw_touch(void)
{
  const touch_state_t *t = touch_state();
  char line[32];
  uint16_t W = epaper_width(), H = epaper_height();
  uint16_t top = (uint16_t)(GFX_CHAR_H * ui_scale() + 5U);
  uint16_t h   = (uint16_t)(H - top - 33U);
  uint16_t bw  = (uint16_t)((W - 8U - 2U * 4U) / 3U);

  draw_title("Touch sensor");
  for (uint8_t i = 0; i < 3; i++)
  {
    uint16_t x = (uint16_t)(4U + i * (bw + 4U));
    if (t->zone == (int8_t)i) epaper_fill_rect(x, top, bw, h, EPAPER_BLACK);
    else                      epaper_rect(x, top, bw, h, EPAPER_BLACK);
  }
  if (touch_ok)
  {
    snprintf(line, sizeof(line), "raw  %u %u %u", t->raw[0], t->raw[1], t->raw[2]);
    gfx_text(2, (uint16_t)(top + h + 3U), line, 1, EPAPER_BLACK);
    snprintf(line, sizeof(line), "base %u %u %u", t->base[0], t->base[1], t->base[2]);
    gfx_text(2, (uint16_t)(top + h + 12U), line, 1, EPAPER_BLACK);
  }
  else
  {
    gfx_text(2, (uint16_t)(top + h + 3U),  "No TSC counts. Check CubeMX", 1, EPAPER_BLACK);
    gfx_text(2, (uint16_t)(top + h + 12U), "TSC groups / IO roles.", 1, EPAPER_BLACK);
  }
  draw_footer("Touch the sensor. B1: back");
  shown_zone = t->zone;
}

