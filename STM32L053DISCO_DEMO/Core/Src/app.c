/* Fine, irregular threshold 0..255 for Example 6 (integer form of
 * "interleaved gradient noise": frac(52.98 * frac(0.0671 x + 0.00584 y))).
 * Blue-noise-like, so it reads as grain instead of a grid or diagonals. */
static uint8_t g16_noise(uint16_t x, uint16_t y)
{
  uint32_t v = ((uint32_t)x * 4398U + (uint32_t)y * 383U) & 0xFFFFU;
  return (uint8_t)(((v * 53U) >> 8) & 0xFFU);
}

/* Example 6: black -> white across the full width, same layout as Example 4.
 * Each column's target is a brightness that rises linearly from the darkest
 * to the lightest entry of g16_ramp; the pixel takes one of the two ramp
 * states that bracket it, picked by g16_noise() in the right proportion. The
 * two candidates are neighbours in brightness, so the texture is only as
 * strong as the step between them (at most ~20 of 255 here; Example 4 mixes
 * shades ~70 apart). */
static void draw_example6_smooth(void)
{
  uint16_t w = epaper_width(), h = epaper_height();
  uint8_t  s = ui_scale();
  uint16_t top      = (uint16_t)(GFX_CHAR_H * s + 5U);
  uint16_t footer_y = (uint16_t)(h - 9U);
  int32_t  b_lo = g16_ramp[0].b, b_hi = g16_ramp[G16_RAMP_N - 1U].b;

  epaper_clear(EPAPER_WHITE);
  draw_title("Example 6 - Smooth");

  for (uint16_t x = 0; x < w; x++)
  {
    int32_t target = b_lo * 256 + ((b_hi - b_lo) * 256 * (int32_t)x) / (int32_t)(w - 1U);   /* 8.8 */
    uint8_t i = 0;
    while (i < G16_RAMP_N - 2U && target >= (int32_t)g16_ramp[i + 1U].b * 256) i++;

    int32_t lo   = (int32_t)g16_ramp[i].b * 256;
    int32_t span = (int32_t)g16_ramp[i + 1U].b * 256 - lo;
    int32_t frac = (span > 0) ? ((target - lo) * 256) / span : 0;   /* share of the lighter state */
    if (frac > 255) frac = 255;

    uint8_t dark  = g16_ramp[i].n;
    uint8_t light = g16_ramp[i + 1U].n;
    for (uint16_t y = top; y < footer_y; y++)
      epaper_set_pixel(x, y, EPAPER_FRAMES((frac > (int32_t)g16_noise(x, y)) ? light : dark));
  }

  draw_footer("BLACK ---------------> WHITE");
}

/* Input ---------------------------------------------------------------------*/

/* Poll B1 (short / long press, reported on release) and the touch sensor
 * (left / middle / right, reported once per touch). Returns EV_NONE if
 * nothing happened. */
static event_t input_poll(void)
{
  static bool     down;
  static uint32_t t_down, t_touch;
  static int8_t   last_zone = -1;
  uint32_t now = HAL_GetTick();

  bool p = board_button_pressed();
  if (p && !down) { down = true; t_down = now; }
  else if (!p && down)
  {
    down = false;
    uint32_t d = now - t_down;
    if (d >= APP_BUTTON_DEBOUNCE_MS) return (d >= APP_LONG_PRESS_MS) ? EV_LONG : EV_SHORT;
  }

  if (touch_ok && (now - t_touch) >= APP_TOUCH_POLL_MS)
  {
    t_touch = now;
    if (touch_scan())
    {
      int8_t z = touch_state()->zone;
      bool fresh = (z >= 0) && (last_zone < 0);
      last_zone = z;
      if (fresh) return (z == 0) ? EV_LEFT : (z == 1) ? EV_MID : EV_RIGHT;
    }
  }
  return EV_NONE;
}

/* Maximum Framerate (experimental) ------------------------------------------
 *
 * Alternates two bar patterns through the epaper_fast_*() path while showing
 * the achieved frame rate. B1 or touch selects the next (faster) level; a long
 * press or a touch on the left stops the test.
 */
/* Fill the framebuffer with the next frame: bars (memset, no per-pixel work)
 * plus a small readout box. Called while the panel is busy with the previous
 * frame, so its cost is hidden behind the refresh. */
static void maxfps_render(uint8_t phase, uint8_t level, uint32_t fps_x10)
{
  char txt[28];
  epaper_fast_pattern(phase);
  snprintf(txt, sizeof(txt), "L%u/%u N=%u  %lu.%lu fps",
           (unsigned)(level + 1U), (unsigned)EPAPER_FAST_LEVELS,
           (unsigned)epaper_fast_level_frames(level),
           (unsigned long)(fps_x10 / 10U), (unsigned long)(fps_x10 % 10U));
  uint16_t w = (uint16_t)(gfx_text_width(txt, 1) + 6U);
  epaper_fill_rect(4, 4, w, 13, EPAPER_WHITE);
  epaper_rect(4, 4, w, 13, EPAPER_BLACK);
  gfx_text(7, 8, txt, 1, EPAPER_BLACK);
}

static void run_maxfps(void)
{
  uint8_t  level = 0U, phase = 0U, win_frames = 0U;
  uint32_t win_t0, fps_x10 = 0U;
  bool     quit = false;

  if (!epaper_fast_begin())
  {
    board_log("maxfps: unavailable (GDEY0213B74 / EPAPER_DISPLAY=1 only) or BUSY timeout");
    epaper_fast_end();
    return;
  }
  board_log("maxfps: start, level 1/%u", (unsigned)EPAPER_FAST_LEVELS);

  maxfps_render(phase, level, fps_x10);
  win_t0 = HAL_GetTick();

  while (!quit)
  {
    epaper_fast_frame_start();                   /* send this frame, start refresh */
    phase ^= 1U;
    maxfps_render(phase, level, fps_x10);        /* next frame, drawn during the refresh */

    event_t  ev = EV_NONE;
    uint32_t t0 = HAL_GetTick();
    while (epaper_fast_busy())                   /* the one wait the panel needs */
    {
      event_t e = input_poll();
      if (e != EV_NONE) ev = e;
      if ((HAL_GetTick() - t0) > APP_FPS_BUSY_TIMEOUT_MS) fatal("e-paper BUSY timeout in max-fps test");
    }

    if (++win_frames >= MAXFPS_WINDOW_FRAMES)
    {
      uint32_t now = HAL_GetTick();
      uint32_t dt  = now - win_t0;
      if (dt == 0U) dt = 1U;
      fps_x10 = ((uint32_t)win_frames * 10000UL) / dt;
      board_log("maxfps: level %u/%u (N=%u): %lu.%lu fps",
                (unsigned)(level + 1U), (unsigned)EPAPER_FAST_LEVELS,
                (unsigned)epaper_fast_level_frames(level),
                (unsigned long)(fps_x10 / 10U), (unsigned long)(fps_x10 % 10U));
      win_frames = 0U;
      win_t0 = now;
    }

    if (ev == EV_LONG || ev == EV_LEFT)
    {
      quit = true;
    }
    else if (ev != EV_NONE)                      /* next (faster) level, wraps to level 1 */
    {
      level = (uint8_t)((level + 1U) % EPAPER_FAST_LEVELS);
      if (!epaper_fast_set_level(level)) fatal("e-paper BUSY timeout in max-fps test");
      fps_x10 = 0U;
      win_frames = 0U;
      win_t0 = HAL_GetTick();
    }
  }

  epaper_fast_end();                             /* normal SPI speed + full re-init on next update */
  board_log("maxfps: stopped");
}

