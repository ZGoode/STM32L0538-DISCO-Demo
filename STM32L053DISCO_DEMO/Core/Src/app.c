/* Extreme Graphics (experimental) ------------------------------------------
 *
 * Drives the panel through the same epaper_extreme_*() path as Extreme FPS,
 * but every frame is real drawing (rectangles, a circle, lines, a scrolling
 * text, a frame counter and a moving box) produced with the normal
 * epaper_*() / gfx_*() calls, instead of the flashing bars of
 * epaper_extreme_pattern().
 */

/* Triangle wave 0..range, taking `period` frames to rise and another `period`
 * to fall. Gives each animated element its own pace from the frame counter
 * alone, without per-element direction state. */
static uint16_t bounce_pos(uint32_t frame, uint16_t range, uint16_t period)
{
  if (period == 0U) period = 1U;
  uint32_t t = frame % (uint32_t)(2U * period);
  uint32_t d = (t <= period) ? t : (uint32_t)(2U * period - t);
  return (uint16_t)(((uint32_t)d * range) / period);
}

/* Fill the framebuffer with the next frame. Called while the panel is busy
 * with the previous frame, so its cost is hidden behind the refresh, as in
 * maxfps_render() / extremefps_render(). Every element moves at its own pace
 * (a different bounce_pos() period and phase each; the marquee scrolls), so
 * no pixel region stays at one state for the length of the test. */
static void extremegfx_render(uint32_t frame, uint16_t mx, uint32_t fps_x10)
{
  uint16_t w = epaper_width(), h = epaper_height();
  char     txt[36];
  static const char marquee[] = "EXTREME GRAPHICS -- STRESS TEST -- ";

  epaper_clear(EPAPER_WHITE);

  /* Status readout: the box of Maximum Framerate / Extreme FPS, showing the
   * frame counter. It also jitters by a few pixels on its own schedule. */
  snprintf(txt, sizeof(txt), "F=%lu  %lu.%lu fps",
           (unsigned long)frame, (unsigned long)(fps_x10 / 10U), (unsigned long)(fps_x10 % 10U));
  uint16_t tw    = (uint16_t)(gfx_text_width(txt, 1) + 6U);
  uint16_t box_x = (uint16_t)(4U + bounce_pos(frame, 3U, 13U));
  uint16_t box_y = (uint16_t)(4U + bounce_pos(frame + 7U, 3U, 19U));
  epaper_fill_rect(box_x, box_y, tw, 13, EPAPER_WHITE);
  epaper_rect(box_x, box_y, tw, 13, EPAPER_BLACK);
  gfx_text((uint16_t)(box_x + 3U), (uint16_t)(box_y + 4U), txt, 1, EPAPER_BLACK);

  uint16_t top    = 20U;
  uint16_t cbot   = (uint16_t)(h - 24U);    /* bottom of the shapes/lines area */

  /* Rectangles (outline and filled), bobbing up and down together. */
  uint16_t rect_y = (uint16_t)(top + bounce_pos(frame, 6U, 25U));
  epaper_rect     (4,  rect_y, 34, 14, EPAPER_BLACK);
  epaper_fill_rect(42, rect_y, 34, 14, EPAPER_BLACK);
  epaper_rect     (80, rect_y, 26, 14, EPAPER_BLACK);

  /* Circle: sweeps left and right across its own lane, clear of the rectangles. */
  uint16_t circ_min   = 110U;
  uint16_t circ_max   = (uint16_t)((w > (circ_min + 15U)) ? (w - 15U) : (circ_min + 1U));
  uint16_t circ_range = (uint16_t)(circ_max - circ_min);
  uint16_t circ_cx    = (uint16_t)(circ_min + bounce_pos(frame, circ_range, 47U));
  epaper_fill_circle(circ_cx, (uint16_t)(top + 7U), 7, EPAPER_BLACK);

  /* Lines: the horizontal line bobs vertically, the diagonal slides up and down
   * within its own band, and the vertical line sweeps across the circle's lane
   * out of step with it (different period and phase). */
  uint16_t hline_y = (uint16_t)(top + 18U + bounce_pos(frame, 6U, 17U));
  epaper_hline(4, hline_y, (uint16_t)(w - 8U), EPAPER_BLACK);
  uint16_t vline_x = (uint16_t)(circ_min + bounce_pos(frame + 20U, circ_range, 39U));
  epaper_vline(vline_x, top, (uint16_t)(cbot - top), EPAPER_BLACK);

  uint16_t diag_span = (uint16_t)(cbot - top - 8U);
  uint16_t diag_top  = (uint16_t)(top + bounce_pos(frame, 8U, 33U));
  for (uint16_t x = 4; x < (uint16_t)(w - 4U); x++)
  {
    uint16_t yy = (uint16_t)(diag_top + ((uint32_t)(x - 4U) * diag_span) / (w - 8U));
    epaper_set_pixel(x, yy, EPAPER_BLACK);
  }

  /* Marquee text: scrolls right to left, faster than the other elements.
   * Coordinates off either edge wrap through unsigned underflow;
   * epaper_set_pixel() drops anything outside the panel, so no clipping is
   * needed here (epaper_circle() relies on the same behavior). */
  uint16_t mq_w   = gfx_text_width(marquee, 1);
  uint32_t mq_tot = (uint32_t)w + mq_w;
  uint16_t mq_pos = (uint16_t)((frame * 5U) % mq_tot);
  uint16_t mq_x   = (uint16_t)((int32_t)w - (int32_t)mq_pos);
  gfx_text(mq_x, (uint16_t)(cbot + 4U), marquee, 1, EPAPER_BLACK);

  /* Box bouncing along the bottom lane; its position (mx) changes every frame. */
  epaper_fill_rect(mx, (uint16_t)(h - 10U), 8, 8, EPAPER_BLACK);
}

static void run_extremegfx(void)
{
  uint8_t  level = 0U, win_frames = 0U;
  uint32_t win_t0, fps_x10 = 0U, frame = 0U;
  uint16_t w = epaper_width();
  uint16_t mx_min = 4U, mx_max = (uint16_t)(w - 12U);
  uint16_t mx = mx_min;
  int8_t   mdir = 1;
  bool     quit = false;

  if (!epaper_extreme_begin())
  {
    board_log("extremegfx: unavailable (GDEY0213B74 / EPAPER_DISPLAY=1 only) or BUSY timeout");
    epaper_extreme_end();
    return;
  }
  board_log("extremegfx: start, level 1/%u", (unsigned)EPAPER_EXTREME_LEVELS);

  extremegfx_render(frame, mx, fps_x10);
  win_t0 = HAL_GetTick();

  while (!quit)
  {
    epaper_extreme_frame_start();                /* send this frame, start refresh */
    frame++;
    if (mx <= mx_min) mdir = 1; else if (mx >= mx_max) mdir = -1;
    mx = (uint16_t)(mx + mdir);
    extremegfx_render(frame, mx, fps_x10);       /* next frame, drawn during the refresh */

    event_t  ev = EV_NONE;
    uint32_t t0 = HAL_GetTick();
    while (epaper_extreme_busy())                /* the one wait the panel needs */
    {
      event_t e = input_poll();
      if (e != EV_NONE) ev = e;
      if ((HAL_GetTick() - t0) > APP_FPS_BUSY_TIMEOUT_MS) fatal("e-paper BUSY timeout in extreme-graphics test");
    }

    if (++win_frames >= MAXFPS_WINDOW_FRAMES)
    {
      uint32_t now = HAL_GetTick();
      uint32_t dt  = now - win_t0;
      if (dt == 0U) dt = 1U;
      fps_x10 = ((uint32_t)win_frames * 10000UL) / dt;
      board_log("extremegfx: level %u/%u (%lu MHz, N=%u): %lu.%lu fps",
                (unsigned)(level + 1U), (unsigned)EPAPER_EXTREME_LEVELS,
                (unsigned long)(epaper_extreme_spi_hz() / 1000000UL),
                (unsigned)epaper_extreme_level_frames(level),
                (unsigned long)(fps_x10 / 10U), (unsigned long)(fps_x10 % 10U));
      win_frames = 0U;
      win_t0 = now;
    }

    if (ev == EV_LONG || ev == EV_LEFT)
    {
      quit = true;
    }
    else if (ev != EV_NONE)                      /* next (faster) level, wraps to level 1 */
    {
      level = (uint8_t)((level + 1U) % EPAPER_EXTREME_LEVELS);
      if (!epaper_extreme_set_level(level)) fatal("e-paper BUSY timeout in extreme-graphics test");
      fps_x10 = 0U;
      win_frames = 0U;
      win_t0 = HAL_GetTick();
    }
  }

  epaper_extreme_end();                          /* normal SPI speed + full re-init on next update */
  board_log("extremegfx: stopped");
}

/* Panel Recovery -------------------------------------------------------------
 *
 * Alternates full-screen black and white using only epaper_clear() and
 * epaper_update(), the normal in-spec update path (never epaper_fast_*() or
 * epaper_extreme_*()). Driving every pixel fully to one extreme and then the
 * other with the panel's own waveform is the standard remedy for residual
 * ghosting after partial or out-of-spec updates.
 *
 * It may not clear every case: ghosting after long or repeated out-of-spec
 * drive can take more than one run to fade, and physical panel damage is not
 * repaired by refreshing.
 */
static void run_recovery(void)
{
  board_log("recovery: starting %u black/white flash cycles", (unsigned)RECOVERY_CYCLES);
  for (uint8_t i = 0; i < RECOVERY_CYCLES; i++)
  {
    epaper_clear(EPAPER_BLACK);
    show();
    epaper_clear(EPAPER_WHITE);
    show();
    board_log("recovery: cycle %u/%u done", (unsigned)(i + 1U), (unsigned)RECOVERY_CYCLES);
    if (input_poll() == EV_LONG)
    {
      board_log("recovery: cancelled by user");
      return;                                   /* panel is left white */
    }
  }
  board_log("recovery: finished");
}

/* STOP mode ------------------------------------------------------------------
 *
 * Shows a message, powers the display down (the image stays on the glass),
 * sleeps in STOP mode and waits for a rising edge on B1.
 */
static void enter_stop(void)
{
  epaper_clear(EPAPER_WHITE);
  draw_title("Sleeping (STOP)");
  gfx_text(4, (uint16_t)(GFX_CHAR_H * ui_scale() + 6U), "MCU in STOP, display off", 1, EPAPER_BLACK);
  gfx_text(4, (uint16_t)(GFX_CHAR_H * ui_scale() + 16U), "Press B1 to wake up", 1, EPAPER_BLACK);
  show();

  board_log("Entering STOP; press B1 to wake");
  epaper_power_off();
  board_led_green(false);
  board_led_red(false);

#if APP_STOP_DISABLE_DEBUG
  HAL_DBGMCU_DisableDBGStopMode();
#endif
#if APP_STOP_ULTRA_LOW_POWER
  HAL_PWREx_EnableUltraLowPower();
  HAL_PWREx_EnableFastWakeUp();
#endif

  board_arm_wake();
  do
  {
    HAL_SuspendTick();
    HAL_PWR_EnterSTOPMode(PWR_LOWPOWERREGULATOR_ON, PWR_STOPENTRY_WFI);
    SystemClock_Config();                 /* the system clock runs from MSI after STOP; restore the PLL configuration */
    HAL_ResumeTick();
  } while (!board_wake_flag());
  board_disarm_wake();

  uint32_t t0 = HAL_GetTick();            /* wait (max 2 s) for the wake-up press to end */
  while (board_button_pressed() && (HAL_GetTick() - t0) < 2000U) { }

  board_log("Woke from STOP");
  if (!epaper_power_on()) fatal("e-paper did not come back after STOP");

  epaper_clear(EPAPER_WHITE);
  draw_title("Awake!");
  gfx_text(4, (uint16_t)(GFX_CHAR_H * ui_scale() + 6U), "Woken by B1. Display was", 1, EPAPER_BLACK);
  gfx_text(4, (uint16_t)(GFX_CHAR_H * ui_scale() + 16U), "unpowered while asleep.", 1, EPAPER_BLACK);
  show();
  HAL_Delay(1500);
}

/* Switch to page p and request a redraw. */
static void go(page_t p)
{
  page = p;
  redraw = true;
  disp_stage = 0;
  board_log("page %u", (unsigned)p);
}

/* Public functions ---------------------------------------------------------*/

void app_init(void)
{
  board_log("");
  board_log("STM32L0538-DISCO showcase");
  board_log("E-paper build: EPAPER_DISPLAY=%u -> %s", epaper_display_id(), epaper_name());

  if (!epaper_init()) fatal("epaper_init failed (BUSY stuck) - wrong display selected?");
  draw_splash();
  show();
  board_led_green(true); HAL_Delay(150); board_led_green(false);   /* blink: first refresh succeeded */

  touch_ok = touch_init();
  board_log("touch: %s", touch_ok ? "OK" : "no counts (check TSC config)");

  sel = 0;
  go(PAGE_MENU);
}

void app_run(void)
{
  event_t ev = input_poll();

  switch (page)
  {
    case PAGE_MENU:
      if (ev == EV_SHORT)                        { sel = (uint8_t)((sel + 1U) % MENU_COUNT); redraw = true; }
      else if (ev == EV_LONG)                    { go(menu_page[sel]); }
      break;

    case PAGE_TOUCH:
    {
      const touch_state_t *t = touch_state();
      board_led_green(t->zone >= 0);
      if (ev == EV_SHORT || ev == EV_LONG)       { board_led_green(false); go(PAGE_MENU); }
      else if (t->zone != shown_zone && (HAL_GetTick() - last_touch_draw) >= APP_TOUCH_REDRAW_MS)
      {
        redraw = true;
        last_touch_draw = HAL_GetTick();
      }
      break;
    }

    case PAGE_LEDS:
      if (ev == EV_SHORT || ev == EV_MID)
      {
        led_mode = (uint8_t)((led_mode + 1U) & 3U);
        board_led_green((led_mode & 1U) != 0U);
        board_led_red((led_mode & 2U) != 0U);
        redraw = true;
      }
      else if (ev == EV_LONG || ev == EV_LEFT)   { board_led_green(false); board_led_red(false); led_mode = 0; go(PAGE_MENU); }
      break;

    case PAGE_STOP:
      if (ev == EV_SHORT || ev == EV_MID)        { enter_stop(); go(PAGE_STOP); }
      else if (ev == EV_LONG || ev == EV_LEFT)   { go(PAGE_MENU); }
      break;

    case PAGE_INFO:
      if (ev != EV_NONE)                         { go(PAGE_MENU); }
      break;

    case PAGE_MAXFPS:
      if (ev == EV_LONG || ev == EV_LEFT)        { go(PAGE_MENU); }
      else if (ev != EV_NONE)                    { run_maxfps(); go(PAGE_MENU); }
      break;

    case PAGE_EXTREMEFPS:
      if (ev == EV_LONG || ev == EV_LEFT)        { go(PAGE_MENU); }
      else if (ev != EV_NONE)                    { run_extremefps(); go(PAGE_MENU); }
      break;

    case PAGE_EXTREMEGFX:
      if (ev == EV_LONG || ev == EV_LEFT)        { go(PAGE_MENU); }
      else if (ev != EV_NONE)                    { run_extremegfx(); go(PAGE_MENU); }
      break;

    case PAGE_RECOVERY:
      if (ev == EV_LONG || ev == EV_LEFT)        { go(PAGE_MENU); }
      else if (ev != EV_NONE)                    { run_recovery(); go(PAGE_MENU); }
      break;

    case PAGE_DISPTEST:                          /* Example 1 -> 2 -> ... -> 6 -> menu */
      if (ev == EV_LONG || ev == EV_LEFT)        { go(PAGE_MENU); }
      else if (ev != EV_NONE)
      {
        if (disp_stage + 1U < DISP_STAGE_COUNT)
        {
          disp_stage++;
          redraw = true;
        }
        else                                     { go(PAGE_MENU); }
      }
      break;
  }

  if (redraw)
  {
    redraw = false;
    if (page == PAGE_DISPTEST && disp_stage != 0U)
    {
      static void (*const gray_draw[DISP_STAGE_COUNT])(void) =
        { NULL, draw_example2_4gray, draw_example3_16gray, draw_example4_gradient,
          draw_example5_16smooth, draw_example6_smooth };
      bool ok = (disp_stage >= 4U)
                  ? epaper_update_gray16(gray_draw[disp_stage], g16_max_frames())
                  : epaper_update_gray(gray_draw[disp_stage]);
      if (!ok) fatal("e-paper BUSY timeout on gray update");
    }
    else
    {
      draw_page();
      show();
    }
  }
  HAL_Delay(2);
}
