/**
 * @file    app.c
 * @brief   Showcase application for the STM32L0538-DISCO.
 *
 * A menu on the e-paper display gives access to demonstrations of:
 *   - the e-paper display itself (it holds its image without power)
 *   - the linear touch sensor (TSC)
 *   - the user button B1 and the user LEDs LD3 / LD4
 *   - ultra-low-power STOP mode (display unpowered, wake-up on B1)
 *   - ST-LINK virtual COM port logging (USART1)
 *   - 4-level and multi-pass gray rendering
 *   - experimental fast-refresh modes and a panel recovery routine
 *
 * Input:
 *   B1 short press : next item / action
 *   B1 long press  : select / back
 *   Touch strip    : on pages other than the menu, left = back and
 *                    middle / right = action or next (depending on the page)
 *
 * A full e-paper refresh blocks for a couple of seconds; input pressed during
 * a refresh is ignored.
 */

