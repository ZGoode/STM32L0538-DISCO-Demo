/* Text scale of titles and menu entries: 2 on the larger display. */
static uint8_t ui_scale(void) { return (epaper_height() >= 100U) ? 2U : 1U; }

static void draw_title(const char *t)
{
  uint8_t  s = ui_scale();
  uint16_t h = (uint16_t)(GFX_CHAR_H * s + 2U);
  epaper_fill_rect(0, 0, epaper_width(), h, EPAPER_BLACK);
  gfx_text(3, 2, t, s, EPAPER_WHITE);
}

static void draw_footer(const char *t)
{
  gfx_text(2, (uint16_t)(epaper_height() - 9U), t, 1, EPAPER_BLACK);
}

/* Word-wrap body text to max_w pixels, using gfx_text_width() for measuring.
 * Drawing stops at max_y instead of running past the bottom of the screen;
 * callers keep their text short enough to fit the smaller display. */
static void draw_wrapped(uint16_t x, uint16_t y, uint16_t max_w, uint16_t max_y, const char *text)
{
  uint16_t    lh = (uint16_t)(GFX_CHAR_H + 2U);
  char        line[64];
  size_t      len = 0;
  const char *p = text;

  line[0] = '\0';
  while (*p != '\0' && y <= max_y)
  {
    while (*p == ' ') p++;
    const char *we = p;
    while (*we != '\0' && *we != ' ') we++;
    size_t wlen = (size_t)(we - p);
    if (wlen == 0U) break;
    if (wlen >= sizeof(line)) wlen = sizeof(line) - 1U;

    char trial[64];
    if (len == 0U) snprintf(trial, sizeof(trial), "%.*s", (int)wlen, p);
    else           snprintf(trial, sizeof(trial), "%s %.*s", line, (int)wlen, p);

    if (len != 0U && gfx_text_width(trial, 1) > max_w)
    {
      gfx_text(x, y, line, 1, EPAPER_BLACK);
      y = (uint16_t)(y + lh);
      snprintf(line, sizeof(line), "%.*s", (int)wlen, p);
      len = strlen(line);
    }
    else
    {
      strncpy(line, trial, sizeof(line) - 1U);
      line[sizeof(line) - 1U] = '\0';
      len = strlen(line);
    }
    p = we;
  }
  if (len != 0U && y <= max_y) gfx_text(x, y, line, 1, EPAPER_BLACK);
}

